#!/usr/bin/env python3
"""Generate `mlfi_graph.h` from the committed capture-derived tables.

The provider must not read the repository at runtime.  The pass order, dispatch geometry, uniform
arena offsets and the 92-entry tensor table are small, non-AMD metadata committed under
`tools/mlfi-capture/derived/`; this script turns them into static C arrays.  No shader or model
bytes are read or emitted.

Usage:
    python3 tools/mlfi-provider/gen_graph_header.py [--out PATH]

The provider build (`build.sh`) writes the header into its build directory, so the repository only
carries the generator and the two committed TSVs.  The test runs with `--check` to prove that the
generated graph matches the tables.
"""

import argparse
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PASSES = ROOT / 'tools/mlfi-capture/derived/passes_mlfi_4k_1280x720.tsv'
TENSORS = ROOT / 'tools/mlfi-capture/derived/tensor_4k_1280x720.tsv'

# The four preprocess pipelines the 4K context creates, in the order the capture created them
# (MLFI-CAPTURE.md 4/5).  The fifth row reuses the splat module.
PREPARE_ROLES = ['dilate', 'splat', 'fwdmv', 'splat', 'splat']
PREPARE_SIZES = [80, 64, 144, 64, 64]


def parse_passes(path: Path):
    rows = []
    for line_no, line in enumerate(path.read_text().splitlines()):
        if line_no == 0 or not line:
            continue
        fields = line.split('\t')
        if len(fields) < 10:
            raise SystemExit(f'{path}:{line_no + 1}: expected 10 columns, got {len(fields)}')
        index = int(fields[0])
        if index != len(rows):
            raise SystemExit(f'{path}:{line_no + 1}: row {index} out of order')
        groups = fields[3].split('x')
        if len(groups) != 3:
            raise SystemExit(f'{path}:{line_no + 1}: bad groups {fields[3]!r}')
        rows.append({
            'index': index,
            'stage': fields[1],
            'entry': fields[2],
            'groups': tuple(int(v) for v in groups),
            'tensor_offset': int(fields[7]),
            'constants_offset': int(fields[8]),
        })
    if len(rows) != 196:
        raise SystemExit(f'{path}: expected 196 rows, got {len(rows)}')
    for row in rows[:5]:
        if row['stage'] != 'prepare' or row['entry'] != 'main':
            raise SystemExit(f"prepare row {row['index']} is {row['stage']}/{row['entry']}")
        if row['tensor_offset'] != 0:
            raise SystemExit(f"prepare row {row['index']} unexpectedly binds CsTensorSizes")
    for i, row in enumerate(rows):
        if i >= 5 and (row['stage'] != 'framegen' or not row['entry'].startswith('mlfi_4k_pass')):
            raise SystemExit(f"framegen row {row['index']} is {row['stage']}/{row['entry']}")
    return rows


def parse_tensors(path: Path):
    entries = []
    for line_no, line in enumerate(path.read_text().splitlines()):
        if line_no == 0 or not line:
            continue
        fields = line.split('\t')
        if len(fields) != 5:
            raise SystemExit(f'{path}:{line_no + 1}: expected 5 columns')
        index = int(fields[0])
        if index != len(entries):
            raise SystemExit(f'{path}:{line_no + 1}: entry {index} out of order')
        entries.append(tuple(int(v) for v in fields[1:]))
    if len(entries) != 92:
        raise SystemExit(f'{path}: expected 92 entries, got {len(entries)}')
    return entries


def generate() -> str:
    passes = parse_passes(PASSES)
    tensors = parse_tensors(TENSORS)
    lines = [
        '// Generated by tools/mlfi-provider/gen_graph_header.py. Do not edit by hand.',
        '//',
        '// Source: tools/mlfi-capture/derived/passes_mlfi_4k_1280x720.tsv and',
        '//         tools/mlfi-capture/derived/tensor_4k_1280x720.tsv (capture metadata only:',
        '//         pass names, group counts, arena offsets and tensor dimensions).',
        '#pragma once',
        '#include <stdint.h>',
        '',
        'typedef struct MlfiRow {',
        '    const char* entry;',
        '    uint32_t    gx, gy, gz;',
        '    uint32_t    prepare;          /* 1 for the five preprocess rows, 0 for model passes */',
        '    uint32_t    prepare_role;     /* 0 dilate, 1 splat, 2 fwdmv */',
        '    uint32_t    constants_size;   /* uniform block size in bytes */',
        '    uint64_t    tensor_offset;    /* arena offset of CsTensorSizes, 0 when unused */',
        '    uint64_t    constants_offset; /* arena offset of the pass uniform block, 0 when unused */',
        '} MlfiRow;',
        '',
        f'#define MLFI_GRAPH_ROW_COUNT {len(passes)}u',
        f'#define MLFI_GRAPH_MODEL_ROWS {len(passes) - 5}u',
        '',
        'static const MlfiRow g_mlfi_rows[MLFI_GRAPH_ROW_COUNT] = {',
    ]
    for row in passes:
        if row['index'] < 5:
            role = PREPARE_ROLES[row['index']]
            role_index = {'dilate': 0, 'splat': 1, 'fwdmv': 2}[role]
            entry = 'main'
            prepare = 1
            constants_size = PREPARE_SIZES[row['index']]
        else:
            role_index = 0
            entry = row['entry']
            prepare = 0
            constants_size = 80 if row['constants_offset'] else 0
        lines.append(
            f'    {{ "{entry}", {row["groups"][0]}u, {row["groups"][1]}u, {row["groups"][2]}u, '
            f'{prepare}u, {role_index}u, {constants_size}u, '
            f'{row["tensor_offset"]}ull, {row["constants_offset"]}ull }},')
    lines += [
        '};',
        '',
        'static const uint32_t g_mlfi_tensor[92][4] = {',
    ]
    for entry in tensors:
        lines.append('    { %su, %su, %su, %su },' % entry)
    lines += [
        '};',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', type=Path, help='write here (default: stdout)')
    parser.add_argument('--check', action='store_true',
                        help='compare an existing --out file instead of writing it')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not args.out:
            raise SystemExit('--check requires --out')
        if not args.out.is_file() or args.out.read_text() != text:
            print(f'{args.out} does not match the committed tables', file=sys.stderr)
            return 1
        print(f'{args.out} matches the committed tables')
        return 0
    if args.out:
        args.out.write_text(text)
        print(f'wrote {args.out}')
    else:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
