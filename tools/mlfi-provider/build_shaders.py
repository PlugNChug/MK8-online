#!/usr/bin/env python3
"""Compile the MLFI provider's own shaders into `mlfi_shaders.h`.

These four shaders are ours (MK8-online), not AMD code: they move the application's inputs into
the provider's images and copy `rw_prediction` to the application's output.  The vendor's final
composition pass was never captured, so the provider composes the frame itself.

The generated header is committed so that building the provider only needs a C compiler; run this
script after editing anything under `shaders/`.

Usage:
    python3 tools/mlfi-provider/build_shaders.py [--check]

`--check` recompiles into a temporary directory and fails if the committed header differs, which
is what the test suite uses to keep the header and the GLSL in sync.
"""

import argparse
import hashlib
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
SHADER_DIR = HERE / 'shaders'
OUTPUT = HERE / 'mlfi_shaders.h'


def compile_shader(source: Path, out: Path, stage: str) -> bytes:
    command = ['glslangValidator', '-V', '--target-env', 'vulkan1.2']
    if stage == 'vert':
        command += ['-S', 'vert']
    elif stage == 'frag':
        command += ['-S', 'frag']
    else:
        command += ['-S', 'comp']
    command += ['-o', str(out), str(source)]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f'{source}: glslangValidator failed:\n{result.stdout}\n{result.stderr}')
    return out.read_bytes()


def c_array(name: str, data: bytes) -> str:
    lines = [f'static const uint32_t {name}[] = {{']
    words = len(data) // 4
    if len(data) % 4:
        raise SystemExit(f'{name}: SPIR-V size {len(data)} is not a multiple of 4')
    for base in range(0, words, 6):
        chunk = data[base * 4:(base + 6) * 4]
        values = ', '.join(f'0x{int.from_bytes(chunk[i:i + 4], "little"):08x}u'
                           for i in range(0, len(chunk), 4))
        lines.append(f'    {values},')
    lines.append('};')
    return '\n'.join(lines)


FILES = [
    ('rgba', 'copy_rgba.comp', 'comp'),
    ('rg16f', 'copy_rg16f.comp', 'comp'),
    ('r32f', 'copy_r32f.comp', 'comp'),
    ('compose_vert', 'compose.vert', 'vert'),
    ('compose_frag', 'compose.frag', 'frag'),
]


def generate() -> str:
    if not shutil.which('glslangValidator'):
        raise SystemExit('glslangValidator not found (install glslang / Vulkan SDK)')
    parts = [
        '// Generated by tools/mlfi-provider/build_shaders.py. Do not edit by hand.',
        '//',
        '// Shader source: tools/mlfi-provider/shaders/*.glsl. These shaders are part of the',
        '// MK8-online MLFI provider, not AMD\'s effect: they move the application inputs into the',
        '// provider images and compose `rw_prediction` into the application output. The vendor',
        '// composition pass was not captured (docs/en/reports/MLFI-PROVIDER.md).',
        '//',
        '// Regenerate with: python3 tools/mlfi-provider/build_shaders.py',
        '#pragma once',
        '#include <stdint.h>',
        '',
    ]
    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        for name, filename, stage in FILES:
            source = SHADER_DIR / filename
            data = compile_shader(source, tmpdir / f'{filename}.spv', stage)
            digest = hashlib.sha256(source.read_bytes()).hexdigest()
            parts.append(f'// {filename} (sha256 {digest})')
            parts.append(c_array(f'mlfi_spv_{name}', data))
            parts.append(f'static const size_t mlfi_spv_{name}_size = sizeof(mlfi_spv_{name});')
            parts.append('')
    return '\n'.join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true',
                        help='fail if the committed header is out of date')
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.is_file() else ''
        if current != text:
            print(f'{OUTPUT} is out of date; run tools/mlfi-provider/build_shaders.py', file=sys.stderr)
            return 1
        print(f'{OUTPUT} is up to date')
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT} ({len(text)} bytes)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
