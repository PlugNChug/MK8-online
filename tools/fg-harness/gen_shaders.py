#!/usr/bin/env python3
"""Compile tools/fg-harness/shaders/*.glsl to SPIR-V and embed it in shaders.h.

The harness itself has no shader-compiler dependency at build time: this script is the only thing
that needs glslangValidator, and its output (shaders.h) is committed. Re-run after editing the
shaders.
"""
import shutil
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHADERS = HERE / 'shaders'
OUTPUT = HERE / 'shaders.h'

SOURCES = [
    ('pattern_vert', SHADERS / 'pattern.vert', 'vert'),
    ('pattern_frag', SHADERS / 'pattern.frag', 'frag'),
]


def compile_stage(source: Path, stage: str, output: Path) -> None:
    subprocess.run(
        [shutil.which('glslangValidator') or 'glslangValidator', '-V', '--target-env', 'vulkan1.2',
         '-S', stage, str(source), '-o', str(output)],
        check=True, capture_output=True, text=True)


def words(path: Path):
    data = path.read_bytes()
    if len(data) % 4:
        raise SystemExit(f'{path}: SPIR-V length is not a multiple of four')
    return struct.unpack(f'<{len(data) // 4}I', data)


def emit(entries) -> None:
    lines = [
        '// Generated by tools/fg-harness/gen_shaders.py -- do not edit.',
        '//',
        '// Source: tools/fg-harness/shaders/pattern.vert and pattern.frag.',
        '// Build: glslangValidator -V --target-env vulkan1.2 -S <stage> <source> -o <out.spv>',
        '#pragma once',
        '#include <cstdint>',
        '',
    ]
    for name, _source, _stage, spirv in entries:
        lines.append(f'static const uint32_t {name}_spirv[] = {{')
        for i in range(0, len(spirv), 8):
            lines.append('    ' + ', '.join(f'0x{word:08x}u' for word in spirv[i:i + 8]) + ',')
        lines.append('};')
        lines.append(f'static const uint32_t {name}_spirv_size = {len(spirv) * 4};')
        lines.append('')
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')


def main() -> int:
    if not shutil.which('glslangValidator'):
        print('glslangValidator not found', file=sys.stderr)
        return 1
    entries = []
    for name, source, stage in SOURCES:
        temporary = HERE / f'.{name}.spv'
        compile_stage(source, stage, temporary)
        entries.append((name, source, stage, words(temporary)))
        temporary.unlink()
    emit(entries)
    print(f'wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
