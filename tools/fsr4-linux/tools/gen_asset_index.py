#!/usr/bin/env python3
"""Generate src/provider/asset_index.hpp (blob id -> shader filename).

Reads build/assets/catalog_final.json and writes the id -> file mapping used by
the native provider to load SPIR-V from FSR4_ASSET_DIR.

Usage: python3 tools/gen_asset_index.py [catalog.json] [output.hpp]
"""

import json
import os
import sys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        here, "..", "build", "assets", "catalog_final.json")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        here, "..", "src", "provider", "asset_index.hpp")
    catalog = json.load(open(src))
    entries = {}
    for c in catalog:
        entries[c["id"]] = os.path.basename(c["file"])

    lines = [
        "// Generated by tools/gen_asset_index.py - do not edit.",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace fsr4_412 {",
        "",
        "struct AssetEntry {",
        "    uint32_t id;",
        "    const char* file;",
        "};",
        "",
        "inline constexpr AssetEntry kAssetIndex[] = {",
    ]
    for blob_id in sorted(entries):
        lines.append(f'    {{{blob_id}, "{entries[blob_id]}"}},')
    lines += [
        "};",
        "",
        "inline const char* assetFile(uint32_t id) {",
        "    for (const AssetEntry& e : kAssetIndex)",
        "        if (e.id == id) return e.file;",
        "    return nullptr;",
        "}",
        "",
        "} // namespace fsr4_412",
        "",
    ]
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "w").write("\n".join(lines))
    print(f"wrote {dst} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
