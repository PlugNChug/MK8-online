#!/usr/bin/env python3
"""Generate src/abi/fsr4_412_selector_table.hpp from the recovered selector map.

The map (tools/data/fsr4_412_selector_map.json) was recovered from the signed
DLL: per-pass/bucket blob ids, the 64-entry prepass key map, the postpass
colour/exposure table, and the SPD/RCAS variants. It contains only blob ids and
hashes, no AMD code.

Usage: python3 tools/gen_selector_table.py [map.json] [output.hpp]
"""

import json
import os
import sys

PASS_ORDER = [
    "prepass", "pass0_post", "pass1", "pass1_post", "pass2", "pass2_post",
    "pass3", "pass3_post", "pass4", "pass4_post", "pass5", "pass5_post",
    "pass6", "pass6_post", "pass7", "pass7_post", "pass8", "pass8_post",
    "pass9", "pass9_post", "pass10", "pass10_post", "pass11", "pass11_post",
    "pass12", "pass12_post", "postpass",
]
# RCAS variants by (colour, auto_exposure). Validated by the selection study.
RCAS = {(0, 0): 327, (1, 0): 330, (2, 0): 328, (3, 0): 324, (0, 1): 325,
        (1, 1): 330, (2, 1): 328, (3, 1): 324}
SPD_ID = 329


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        here, "data", "fsr4_412_selector_map.json")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        here, "..", "src", "abi", "fsr4_412_selector_table.hpp")
    data = json.load(open(src))

    passes = data["passes"]
    prepass = data["prepass_key_table"]
    postpass = data["postpass"]

    lines = []
    lines.append("// Generated by tools/gen_selector_table.py — do not edit.")
    lines.append("// Source: tools/data/fsr4_412_selector_map.json")
    lines.append("// SPDX-License-Identifier: GPL-3.0-only")
    lines.append("#pragma once")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace fsr4_412 {")
    lines.append("")
    lines.append("enum class PassId : uint32_t {")
    for i, name in enumerate(PASS_ORDER):
        lines.append(f"    k{i}_{name} = {i},")
    lines.append("};")
    lines.append("")
    lines.append("// Blob ids per canonical pass (skip index 0 and 26 for keyed passes).")
    lines.append("inline constexpr uint32_t kPassBlob[27][3] = {")
    for name in PASS_ORDER:
        row = []
        for bucket in range(3):
            entry = passes[name].get(str(bucket))
            row.append(entry["id"] if entry else 0)
        lines.append(f"    {{{row[0]}, {row[1]}, {row[2]}}}, // {name}")
    lines.append("};")
    lines.append("")
    lines.append("// Prepass: [key 0..63][bucket 0..2].")
    lines.append("inline constexpr uint32_t kPrepassBlob[64][3] = {")
    for key in range(64):
        row = []
        for bucket in range(3):
            row.append(prepass[str(bucket)]["key_to_id"][str(key)])
        lines.append(f"    {{{row[0]}, {row[1]}, {row[2]}}},")
    lines.append("};")
    lines.append("")
    lines.append("// Postpass: [(colour << 1) | auto_exposure][bucket].")
    lines.append("inline constexpr uint32_t kPostpassBlob[8][3] = {")
    for idx in range(8):
        colour, ae = idx >> 1, idx & 1
        row = []
        for bucket in range(3):
            row.append(postpass[str(bucket)].get(f"{colour},{ae}", 0))
        lines.append(f"    {{{row[0]}, {row[1]}, {row[2]}}}, // colour={colour} ae={ae}")
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr uint32_t kSpdBlobId = {SPD_ID};")
    lines.append("")
    lines.append("// RCAS: [(colour << 1) | auto_exposure].")
    lines.append("inline constexpr uint32_t kRcasBlob[8] = {")
    for idx in range(8):
        colour, ae = idx >> 1, idx & 1
        lines.append(f"    {RCAS[(colour, ae)]}, // colour={colour} ae={ae}")
    lines.append("};")
    lines.append("")
    lines.append("inline uint32_t selectPassBlob(uint32_t pass, uint32_t bucket, uint32_t key) {")
    lines.append("    if (pass == 0) return kPrepassBlob[key & 63u][bucket];")
    lines.append("    if (pass == 26) {")
    lines.append("        const uint32_t colour = (key >> 3) & 3u;")
    lines.append("        const uint32_t ae = (key >> 2) & 1u;")
    lines.append("        uint32_t v = kPostpassBlob[(colour << 1) | ae][bucket];")
    lines.append("        if (!v) v = kPostpassBlob[colour << 1][bucket];")
    lines.append("        if (!v) v = kPostpassBlob[ae][bucket];")
    lines.append("        if (!v) v = kPostpassBlob[0][bucket];")
    lines.append("        return v;")
    lines.append("    }")
    lines.append("    return kPassBlob[pass][bucket];")
    lines.append("}")
    lines.append("")
    lines.append("inline uint32_t selectRcasBlob(uint32_t key) {")
    lines.append("    return kRcasBlob[(((key >> 3) & 3u) << 1) | ((key >> 2) & 1u)];")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace fsr4_412")
    lines.append("")

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    open(dst, "w").write("\n".join(lines))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
