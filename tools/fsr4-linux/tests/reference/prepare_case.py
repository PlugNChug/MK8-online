#!/usr/bin/env python3
"""Turn a reference trace directory into a native-runner manifest.

Usage:
  prepare_case.py <trace-dir> <assets-dir> <out-dir>

The trace directory is produced by tests/reference/fsr4_trace.c (trace.txt,
tensor.bin, constants.bin, in_*.raw, out_color.rgba8). The assets directory is
the extractor output (catalog_final.json + shaders/). The manifest is written to
<out-dir>/case.txt and points at absolute paths, so the runner can be invoked
from anywhere.
"""

import argparse
import json
import os
import re
import shutil
import sys


def parse_trace(trace_path):
    current_pipeline = None
    pipelines = {}
    dispatches = []
    with open(trace_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = re.match(r"PIPELINE handle=(\S+) shader=\S+ sha256=(\w+) entry=(\S+)", line)
            if m:
                pipelines[m.group(1)] = (m.group(2), m.group(3))
                continue
            m = re.match(r"BINDPIPE cb=\S+ pipeline=(\S+) shader=\S+ entry=(\S+)", line)
            if m:
                current_pipeline = m.group(1)
                continue
            m = re.match(r"DISPATCH n=(\d+) cb=\S+ groups=(\d+),(\d+),(\d+)", line)
            if m:
                dispatches.append(
                    {
                        "index": int(m.group(1)),
                        "groups": [int(m.group(2)), int(m.group(3)), int(m.group(4))],
                        "pipeline": current_pipeline,
                    }
                )
    return pipelines, dispatches


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("trace_dir")
    ap.add_argument("assets_dir")
    ap.add_argument("out_dir")
    args = ap.parse_args()

    trace_dir = os.path.abspath(args.trace_dir)
    assets_dir = os.path.abspath(args.assets_dir)
    out_dir = os.path.abspath(args.out_dir)
    os.makedirs(out_dir, exist_ok=True)

    with open(os.path.join(assets_dir, "catalog_final.json"), "r", encoding="utf-8") as f:
        catalog = json.load(f)
    by_sha = {}
    for entry in catalog:
        by_sha.setdefault(entry["sha256"], entry)

    pipelines, dispatches = parse_trace(os.path.join(trace_dir, "trace.txt"))
    if len(dispatches) < 27:
        print(f"warning: expected at least 27 dispatches, found {len(dispatches)}",
              file=sys.stderr)

    header = []
    with open(os.path.join(trace_dir, "trace.txt"), "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("FSR4_TRACE "):
                parts = line.split()
                header = parts[1:]
                break
    render = output = None
    create_flags = 0
    sharpen = 0
    sharpness = 0.0
    for token in header:
        if token.startswith("render="):
            w, h = token.split("=", 1)[1].split("x")
            render = (int(w), int(h))
        elif token.startswith("output="):
            w, h = token.split("=", 1)[1].split("x")
            output = (int(w), int(h))
        elif token.startswith("create_flags="):
            create_flags = int(token.split("=", 1)[1], 0)
        elif token.startswith("sharpen="):
            sharpen = int(token.split("=", 1)[1])
        elif token.startswith("sharpness="):
            sharpness = float(token.split("=", 1)[1])
    if not render or not output:
        raise SystemExit("could not read render/output sizes from trace.txt")

    # Scratch capacity follows the same resolution classes as fsr4-vk.
    if output[0] > 3840 or output[1] > 2160:
        scratch = 332352256
    elif output[0] > 1920 or output[1] > 1080:
        scratch = 83232256
    else:
        scratch = 20880256

    lines = [
        "# generated by prepare_case.py",
        f"render {render[0]} {render[1]}",
        f"output {output[0]} {output[1]}",
        f"scratch {scratch}",
        f"weights {os.path.join(assets_dir, 'models', 'FP8_standard.bin')}",
        f"tensor {os.path.join(trace_dir, 'tensor.bin')}",
        f"constants {os.path.join(trace_dir, 'constants.bin')}",
        f"color {os.path.join(trace_dir, 'in_color.rgba8')}",
        f"depth {os.path.join(trace_dir, 'in_depth.f32')}",
        f"motion {os.path.join(trace_dir, 'in_mv.rg16f')}",
        f"flags {create_flags}",
        f"sharpen {sharpen}",
        f"sharpness {sharpness}",
    ]

    for dispatch in dispatches:
        pipe = pipelines.get(dispatch["pipeline"])
        if not pipe:
            raise SystemExit(f"missing pipeline for dispatch {dispatch['index']}")
        sha, entry = pipe
        entry_catalog = by_sha.get(sha)
        if not entry_catalog:
            raise SystemExit(f"shader {sha} not in catalog")
        spv = os.path.join(assets_dir, "shaders", os.path.basename(entry_catalog["file"]))
        if not os.path.exists(spv):
            raise SystemExit(f"missing shader {spv}")
        g = dispatch["groups"]
        if entry == "fsr_rcas_pass" or entry_catalog["pass"] == "rcas":
            lines.append(f"rcas {g[0]} {g[1]} {g[2]} {spv} {entry}")
        elif entry_catalog["pass"] == "debug/utility" or entry == "main":
            lines.append(f"spd {g[0]} {g[1]} {g[2]} {spv} {entry}")
        else:
            lines.append(f"pass {entry_catalog['pass']} {g[0]} {g[1]} {g[2]} {spv} {entry}")

    for name, file in (("spdfile", "spd.bin"), ("rcasfile", "rcas.bin")):
        path = os.path.join(trace_dir, file)
        if os.path.exists(path):
            lines.append(f"{name} {path}")

    manifest = os.path.join(out_dir, "case.txt")
    with open(manifest, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # Keep the reference output next to the manifest for compare.py.
    ref = os.path.join(trace_dir, "out_color.rgba8")
    if os.path.exists(ref):
        shutil.copyfile(ref, os.path.join(out_dir, "out_reference.rgba8"))

    print(f"wrote {manifest} ({len(dispatches)} passes)")


if __name__ == "__main__":
    main()
